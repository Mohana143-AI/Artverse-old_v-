    return $AVATAR_POOL[abs($user_id) % count($AVATAR_POOL)];
}

function get_creator_cover(int $user_id = 0, string $cover_image = ''): string {
    global $CREATOR_COVERS;
    if (!empty($cover_image) && (
        str_starts_with($cover_image, 'http') ||
        str_starts_with($cover_image, '/') ||
        str_starts_with($cover_image, 'uploads/') ||
        str_starts_with($cover_image, 'assets/')
    )) {
        return $cover_image;
    }
    return $CREATOR_COVERS[abs($user_id) % count($CREATOR_COVERS)];
}

/**
 * Format currency in Indian Rupee (₹)
 */
function format_price($amount, string $fallback = 'Request Quote'): string {
    if ($amount === null || $amount === '' || (float)$amount <= 0) {
        return $fallback;
    }
    return '₹' . number_format((float)$amount, 2);
}