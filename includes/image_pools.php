/**
 * Get a listing image from the pool.
 * Falls back through: real stored URL → category pool → type fallback → generic art fallback
 */
function get_category_image(string $image_url, string $cat_slug, string $listing_type, int $listing_id = 0): string {
    global $CATEGORY_IMAGE_POOLS;

    // 1. If already a real URL or local path, use it
    if (!empty($image_url) && (
        str_starts_with($image_url, 'http') ||
        str_starts_with($image_url, '/') ||
        str_starts_with($image_url, 'uploads/') ||
        str_starts_with($image_url, 'assets/')
    )) {
        return $image_url;
    }

    // 2. Category pool (30 unique images, rotate by listing_id)
    if (!empty($cat_slug) && isset($CATEGORY_IMAGE_POOLS[$cat_slug])) {
        $pool = $CATEGORY_IMAGE_POOLS[$cat_slug];
        return $pool[abs($listing_id) % count($pool)];
    }

    // 3. Type-based fallback
    $type_fb = [
        'service'      => 'https://images.unsplash.com/photo-1521737604893-d14cc237f11d?w=700&q=82&auto=format&fit=crop',
        'customizable' => 'https://images.unsplash.com/photo-1558618666-fcd25c85cd64?w=700&q=82&auto=format&fit=crop',
        'ready_made'   => 'https://images.unsplash.com/photo-1523275335684-37898b6baf30?w=700&q=82&auto=format&fit=crop',
    ];
    if (!empty($listing_type) && isset($type_fb[$listing_type])) {
        return $type_fb[$listing_type];
    }

    // 4. Generic art fallback
    return 'https://images.unsplash.com/photo-1579783902614-a3fb3927b6a5?w=700&q=82&auto=format&fit=crop';
}

